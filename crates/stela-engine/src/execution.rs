// Bounds a cached artifact so it cannot force an unbounded allocation or
// mapping.
pub(crate) const MAX_NATIVE_BYTES: usize = 64 * 1024 * 1024;

/// An owned RX copy of one registered leaf's code. It is neither Send nor Sync.
#[cfg(feature = "std")]
#[derive(Debug)]
pub struct ExecutableLeaf {
    resolved: ResolvedLeaf,
    mapping: platform::Mapping,
    _serialized: PhantomData<Rc<()>>,
}

#[cfg(feature = "std")]
impl ExecutableLeaf {
    /// Read and hash generated bytes against the immutable resolved manifest,
    /// check the current compiler/ABI/CPU identity, and create an RX mapping.
    ///
    /// The persisted manifest is not reread: external cache edits cannot change
    /// the identity or expected hash held by the resolved handle. An already
    /// loaded mapping remains independent of later disk changes.
    pub fn load(dispatcher: &LeafDispatcher, resolved: &ResolvedLeaf) -> Result<Self> {
        ensure!(
            dispatcher.is_current(resolved),
            "stale or foreign registered leaf"
        );
        let manifest = &resolved.prepared().manifest;
        let identity = &manifest.identity;
        ensure!(
            *identity == resolved.identity().translation,
            "resolved translation identity mismatch"
        );
        ensure!(
            identity.schema_version == 1,
            "unsupported translation schema"
        );
        ensure!(
            identity.compiler_source_sha256 == crate::compiler_source_sha256(),
            "generated code uses a different compiler"
        );
        ensure!(
            identity.abi
                == stela_compiler::block::BlockProfile::new(stela_compiler::block::Features::LEAF)
                    .abi(),
            "unsupported generated-code ABI"
        );
        let target = identity
            .target_cpu
            .parse::<stela_compiler::TargetCpu>()
            .map_err(anyhow::Error::msg)?;
        ensure!(
            crate::platform::cpu::admitted(target),
            "host CPU lacks generated-code requirements {}",
            target.id()
        );
        ensure!(
            !manifest.verified,
            "cache metadata is not verification evidence"
        );
        ensure!(
            manifest.native_bytes > 0 && manifest.native_bytes <= MAX_NATIVE_BYTES,
            "generated-code size exceeds execution bound"
        );
        platform::ensure_supported()?;
        let path = resolved.prepared().directory.join("native.bin");
        let mut bytes = Vec::new();
        std::fs::File::open(&path)
            .with_context(|| format!("open generated artifact {}", path.display()))?
            .take((MAX_NATIVE_BYTES + 1) as u64)
            .read_to_end(&mut bytes)?;
        ensure!(
            bytes.len() == manifest.native_bytes && sha256(&bytes) == manifest.native_sha256,
            "generated artifact differs from resolved immutable manifest"
        );
        let mapping = platform::Mapping::new(&bytes)?;
        // The immutable dispatcher borrow spans validation and publication.
        ensure!(
            dispatcher.is_current(resolved),
            "registered leaf became stale"
        );
        Ok(Self {
            resolved: resolved.clone(),
            mapping,
            _serialized: PhantomData,
        })
    }

    pub fn resolved(&self) -> &ResolvedLeaf {
        &self.resolved
    }

    pub fn native_bytes(&self) -> usize {
        self.resolved.prepared().manifest.native_bytes
    }

    /// Execute this leaf against the ABI's memory-backed guest register state.
    /// Registration is checked immediately before the native call, while this
    /// immutable dispatcher borrow excludes serialized replacement/removal.
    ///
    /// # Safety
    ///
    /// The caller must trust the registered source and generated bytes, and must
    /// establish that this leaf returns in finite time. Every executed guest
    /// load/store must address live ordinary RAM at the identical native virtual
    /// address, with sufficient bounds, permissions and alignment for the direct
    /// RAM profile. RAM must remain live for the entire call. Guest memory cannot
    /// alias `state`, executable bytes, this object, the dispatcher, any live Rust
    /// references, or host metadata/stack. Guest writes require exclusive access
    /// and cannot race other threads. SP-based accesses must satisfy the enabled
    /// ARM alignment checks. No MMIO, PAC/tagged-pointer assumptions, atomicity,
    /// concurrent code mutation, external calls or guest exception delivery are
    /// supported. A guest fault can terminate the host process; this API does not
    /// install a signal handler or sandbox untrusted code.
    pub unsafe fn execute(
        &self,
        dispatcher: &LeafDispatcher,
        state: &mut GuestState,
    ) -> Result<()> {
        ensure!(
            dispatcher.is_current(&self.resolved),
            "refusing stale or foreign native execution"
        );
        // SAFETY: the caller upholds the direct-RAM and termination contract;
        // the mapping is owned, immutable RX with the checked ABI.
        unsafe { self.mapping.call(state) }
    }
}

