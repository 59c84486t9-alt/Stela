//! Lazy resolution of registered leaf entry points. Handles must be revalidated
//! before each execution; invalidation does not interrupt running code.

use crate::{Identity, Prepared, prepare_leaf};
use alloc::collections::BTreeMap;
use alloc::sync::Arc;
#[cfg(not(feature = "std"))]
use alloc::{string::String, vec::Vec};
use anyhow::{Result, ensure};
use std::path::PathBuf;
use stela_compiler::GuestAddress;
use stela_formats::sha256;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DispatchIdentity {
    pub address_space: u64,
    pub mapping_generation: u64,
    pub translation: Identity,
}

/// A generated leaf and its registration identity.
#[derive(Debug, Clone)]
pub struct ResolvedLeaf {
    identity: DispatchIdentity,
    prepared: Arc<Prepared>,
    issuer: Arc<()>,
}

impl ResolvedLeaf {
    pub fn identity(&self) -> &DispatchIdentity {
        &self.identity
    }

    pub fn prepared(&self) -> &Prepared {
        &self.prepared
    }

    /// Associate an offset within generated bytes with its guest instruction.
    /// This does not reconstruct intermediate state or deliver a guest fault.
    pub fn guest_instruction_for_native_offset(&self, offset: usize) -> Option<GuestAddress> {
        let manifest = &self.prepared.manifest;
        if offset >= manifest.native_bytes {
            return None;
        }
        let index = manifest
            .source_map
            .partition_point(|(_, start)| *start <= offset);
        index.checked_sub(1).map(|i| manifest.source_map[i].0)
    }
}

#[derive(Debug)]
struct RegisteredLeaf {
    source: Vec<u8>,
    source_sha256: String,
    end: u64,
    generation: u64,
}

/// Process-local registration and lookup of leaf regions. Each registry also
/// has a private issuer identity, so handles from one never validate in
/// another.
#[derive(Debug)]
pub struct LeafDispatcher {
    address_space: u64,
    cache_root: PathBuf,
    next_generation: u64,
    leaves: BTreeMap<u64, RegisteredLeaf>,
    issuer: Arc<()>,
}

impl LeafDispatcher {
    pub fn new(address_space: u64, cache_root: PathBuf) -> Self {
        Self {
            address_space,
            cache_root,
            next_generation: 0,
            leaves: BTreeMap::new(),
            issuer: Arc::new(()),
        }
    }

    /// Register immutable source bytes; replacing an entry always gives it a
    /// fresh generation, including replacement with byte-identical source.
    /// Unsupported semantics fail later during resolve, without creating code.
    pub fn register(&mut self, entry: GuestAddress, source: Vec<u8>) -> Result<u64> {
        ensure!(
            !source.is_empty() && source.len().is_multiple_of(4) && entry.0.is_multiple_of(4),
            "leaf source and entry must be nonempty and 4-byte aligned"
        );
        let length = u64::try_from(source.len())?;
        let end = entry
            .0
            .checked_add(length)
            .ok_or_else(|| anyhow::anyhow!("leaf range overflow"))?;
        for (&base, leaf) in &self.leaves {
            ensure!(
                base == entry.0 || end <= base || entry.0 >= leaf.end,
                "leaf registration overlaps another registered region"
            );
        }
        let generation = self
            .next_generation
            .checked_add(1)
            .ok_or_else(|| anyhow::anyhow!("mapping generation exhausted"))?;
        let source_sha256 = sha256(&source);
        self.leaves.insert(
            entry.0,
            RegisteredLeaf {
                source,
                source_sha256,
                end,
                generation,
            },
        );
        self.next_generation = generation;
        Ok(generation)
    }

    pub fn unregister(&mut self, entry: GuestAddress) -> bool {
        self.leaves.remove(&entry.0).is_some()
    }

    /// Resolve a registered entry only; interior addresses are not entries.
    /// Persisted checksums are revalidated on every lookup, including disk
    /// hits.
    pub fn resolve(&self, entry: GuestAddress) -> Result<ResolvedLeaf> {
        let leaf = self
            .leaves
            .get(&entry.0)
            .ok_or_else(|| anyhow::anyhow!("unregistered guest entry {:#x}", entry.0))?;
        let prepared = prepare_leaf(&leaf.source, entry, &self.cache_root)?;
        ensure!(
            prepared.manifest.identity.source_sha256 == leaf.source_sha256,
            "registered source identity mismatch"
        );
        validate_source_map(&prepared, entry, leaf.source.len())?;
        Ok(ResolvedLeaf {
            identity: DispatchIdentity {
                address_space: self.address_space,
                mapping_generation: leaf.generation,
                translation: prepared.manifest.identity.clone(),
            },
            prepared: Arc::new(prepared),
            issuer: self.issuer.clone(),
        })
    }

    /// A stale handle remains inspectable, but must not become a live target.
    /// This check is serialized with registry updates via the borrow rules; a
    /// future multi-thread executor needs a separate execution/lifetime guard.
    pub fn is_current(&self, resolved: &ResolvedLeaf) -> bool {
        if !Arc::ptr_eq(&self.issuer, &resolved.issuer)
            || self.address_space != resolved.identity.address_space
        {
            return false;
        }
        let identity = &resolved.identity.translation;
        self.leaves.get(&identity.guest_base).is_some_and(|leaf| {
            leaf.generation == resolved.identity.mapping_generation
                && leaf.source_sha256 == identity.source_sha256
        })
    }
}

fn validate_source_map(
    prepared: &Prepared,
    entry: GuestAddress,
    source_bytes: usize,
) -> Result<()> {
    let manifest = &prepared.manifest;
    ensure!(
        !manifest.verified,
        "generated cache is not verification evidence"
    );
    ensure!(manifest.native_bytes > 0, "empty generated code");
    ensure!(
        manifest.source_map.len() == source_bytes / 4,
        "source map must cover every registered guest instruction"
    );
    let mut previous = None;
    for (index, &(guest, native)) in manifest.source_map.iter().enumerate() {
        let expected = entry
            .0
            .checked_add((index as u64) * 4)
            .ok_or_else(|| anyhow::anyhow!("source map guest address overflow"))?;
        ensure!(guest.0 == expected, "source map guest instruction mismatch");
        ensure!(
            native < manifest.native_bytes,
            "source map offset outside generated code"
        );
        ensure!(
            previous.is_none_or(|p| native > p),
            "source map offsets must increase strictly"
        );
        ensure!(
            index != 0 || native == 0,
            "source map must start at native offset zero"
        );
        previous = Some(native);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source(value: u32) -> Vec<u8> {
        [0xd2800000u32 | (value << 5), 0xd65f03c0]
            .into_iter()
            .flat_map(u32::to_le_bytes)
            .collect()
    }

    #[test]
    fn resolution_keeps_identity_and_instruction_map() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(9, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(42))?;
        let first = registry.resolve(entry)?;
        let second = registry.resolve(entry)?;
        assert!(!first.prepared().cache_hit);
        assert!(second.prepared().cache_hit);
        assert_eq!(first.identity(), second.identity());
        assert!(registry.is_current(&first));
        assert!(!first.prepared().manifest.verified);
        let return_offset = first.prepared().manifest.source_map[1].1;
        assert_eq!(first.guest_instruction_for_native_offset(0), Some(entry));
        assert_eq!(
            first.guest_instruction_for_native_offset(return_offset - 1),
            Some(entry)
        );
        assert_eq!(
            first.guest_instruction_for_native_offset(return_offset),
            Some(GuestAddress(0x1004))
        );
        assert_eq!(
            first.guest_instruction_for_native_offset(first.prepared().manifest.native_bytes),
            None
        );
        assert!(registry.resolve(GuestAddress(0x1004)).is_err());
        assert!(registry.resolve(GuestAddress(0x2000)).is_err());
        Ok(())
    }

    #[test]
    fn replacement_removal_and_identical_address_reuse_invalidate_old_handles() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(40))?;
        let original = registry.resolve(entry)?;
        registry.register(entry, source(41))?;
        assert!(!registry.is_current(&original));
        let updated = registry.resolve(entry)?;
        assert_ne!(original.prepared().key, updated.prepared().key);
        assert!(registry.unregister(entry));
        assert!(!registry.is_current(&updated));
        assert!(!registry.unregister(entry));
        registry.register(entry, source(40))?;
        let reused = registry.resolve(entry)?;
        assert_eq!(original.prepared().key, reused.prepared().key);
        assert_ne!(
            original.identity().mapping_generation,
            reused.identity().mapping_generation
        );
        assert!(!registry.is_current(&original));
        assert!(registry.is_current(&reused));
        registry.register(entry, source(40))?;
        assert!(!registry.is_current(&reused));
        Ok(())
    }

    #[test]
    fn handles_do_not_transfer_between_registries_even_with_same_address_space_id() -> Result<()> {
        let root = tempfile::tempdir()?;
        let entry = GuestAddress(0x1000);
        let mut first = LeafDispatcher::new(1, root.path().into());
        let mut second = LeafDispatcher::new(1, root.path().into());
        first.register(entry, source(40))?;
        second.register(entry, source(40))?;
        let resolved = first.resolve(entry)?;
        assert!(!second.is_current(&resolved));
        assert!(second.resolve(entry)?.prepared().cache_hit);
        Ok(())
    }

    #[test]
    fn invalid_ranges_and_overlaps_leave_registration_intact() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(40))?;
        let original = registry.resolve(entry)?;
        for (base, bytes) in [
            (0x1004, source(41)),
            (0xffc, source(41)),
            (1, source(41)),
            (0x2000, vec![]),
            (0x2000, vec![0]),
            (u64::MAX - 3, source(41)),
        ] {
            assert!(registry.register(GuestAddress(base), bytes).is_err());
        }
        assert!(registry.is_current(&original));
        registry.register(GuestAddress(0x1008), source(41))?;
        assert!(registry.is_current(&original));
        Ok(())
    }

    #[test]
    fn unsupported_semantics_never_resolve_or_publish_a_cache_entry() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, vec![0; 4])?;
        assert!(registry.resolve(entry).is_err());
        assert_eq!(std::fs::read_dir(root.path())?.count(), 0);
        registry.register(entry, source(40))?;
        assert!(registry.resolve(entry).is_ok());
        Ok(())
    }

    #[test]
    fn warm_lookup_rejects_corruption_instead_of_reusing_a_stale_path() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(40))?;
        let resolved = registry.resolve(entry)?;
        std::fs::write(resolved.prepared().directory.join("native.bin"), b"changed")?;
        assert!(registry.resolve(entry).is_err());
        // is_current only answers registration identity, never disk integrity.
        assert!(registry.is_current(&resolved));
        Ok(())
    }

    #[test]
    fn malformed_source_maps_fail_even_with_recomputed_manifest_checksum() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(40))?;
        let resolved = registry.resolve(entry)?;
        let path = resolved.prepared().directory.join("manifest.json");
        let original = std::fs::read(&path)?;
        for variant in 0..5 {
            let mut manifest: crate::Manifest = serde_json::from_slice(&original)?;
            match variant {
                0 => {
                    manifest.source_map.pop();
                }
                1 => manifest.source_map[0].0 = GuestAddress(0x1004),
                2 => manifest.source_map[0].1 = 1,
                3 => manifest.source_map[1].1 = manifest.source_map[0].1,
                _ => manifest.source_map[1].1 = manifest.native_bytes,
            }
            crate::write_json(&path, &manifest)?;
            crate::write_json(
                &resolved.prepared().directory.join("manifest.sha256.json"),
                &sha256(&std::fs::read(&path)?),
            )?;
            assert!(registry.resolve(entry).is_err());
        }
        Ok(())
    }

    #[test]
    fn generation_exhaustion_does_not_replace_a_live_mapping() -> Result<()> {
        let root = tempfile::tempdir()?;
        let mut registry = LeafDispatcher::new(1, root.path().into());
        let entry = GuestAddress(0x1000);
        registry.register(entry, source(40))?;
        let original = registry.resolve(entry)?;
        registry.next_generation = u64::MAX;
        assert!(registry.register(entry, source(41)).is_err());
        assert!(registry.is_current(&original));
        Ok(())
    }
}
