//! Exact EP51/FP52 PHY masks and PWM sequence from pinned Linux.
use super::{BlockError, Hardware, Registers, Timer};
const EP_PARAMETERS: &[(u16, u16, u16)] = &[
    (0x80f3, 0xff00, 0x8b00),
    (0x80f0, 0xff00, 0x3a00),
    (0x80ef, 0xff00, 0x0500),
    (0x80f6, 0xff00, 0x6e00),
    (0x80ec, 0xff00, 0x6800),
    (0x80ed, 0xff00, 0x7c00),
    (0x80f2, 0xff00, 0xf400),
    (0x80f4, 0xff00, 0x8500),
    (0x8110, 0xff00, 0xa800),
    (0x810f, 0xff00, 0x1d00),
    (0x8111, 0xff00, 0xf500),
    (0x8113, 0xff00, 0x6100),
    (0x8115, 0xff00, 0x9200),
    (0x810e, 0xff00, 0x0400),
    (0x810c, 0xff00, 0x7c00),
    (0x810b, 0xff00, 0x5a00),
    (0x80d1, 0xff00, 0xff00),
    (0x80cd, 0xff00, 0x9e00),
    (0x80d3, 0xff00, 0x0e00),
    (0x80d5, 0xff00, 0xca00),
    (0x80d7, 0xff00, 0x8400),
];
const FP_PARAMETERS: &[(u16, u16, u16)] = &[
    (0x808e, 0xff00, 0x4800),
    (0x8090, 0xff00, 0xcc00),
    (0x8092, 0xff00, 0xb000),
    (0x8088, 0xff00, 0x6000),
    (0x808b, 0x3f00, 0x0b00),
    (0x808d, 0x1f00, 0x0600),
    (0x808c, 0xff00, 0xb000),
    (0x80a0, 0xff00, 0x2800),
    (0x80a2, 0xff00, 0x5000),
    (0x809b, 0xf800, 0xb000),
    (0x809a, 0xff00, 0x4b00),
    (0x809d, 0x3f00, 0x0800),
    (0x80a1, 0xff00, 0x7000),
    (0x809f, 0x1f00, 0x0300),
    (0x809e, 0xff00, 0x8800),
    (0x80b2, 0xff00, 0x2200),
    (0x80ad, 0xf800, 0x9800),
    (0x80af, 0x3f00, 0x0800),
    (0x80b3, 0xff00, 0x6f00),
    (0x80b1, 0x1f00, 0x0300),
    (0x80b0, 0xff00, 0x9300),
];
impl<R: Registers, T: Timer> Hardware<'_, R, T> {
    pub(super) fn ep_phy(&self) -> Result<(), BlockError> {
        self.paged(0x0bcc, 0x14, 1 << 8, 0)?;
        self.paged(0x0a44, 0x11, 0, (1 << 7) | (1 << 6))?;
        self.g_parameter(0x8084, 0x6000, 0)?;
        self.paged(0x0a43, 0x10, 0, 0x1003)?;
        self.paged(0x0a4b, 0x11, 0, 1 << 2)?;
        self.g_parameter(0x8012, 0, 0x8000)?;
        self.paged(0x0c42, 0x11, 1 << 13, 1 << 14)?;
        for &(address, clear, set) in EP_PARAMETERS {
            self.g_parameter(address, clear, set)?;
        }
        self.batch(&[
            (0x1f, 0x0bcd),
            (0x14, 0x5065),
            (0x14, 0xd065),
            (0x1f, 0x0bc8),
            (0x12, 0x00ed),
            (0x1f, 0x0bcd),
            (0x14, 0x1065),
            (0x14, 0x9065),
            (0x14, 0x1065),
            (0x1f, 0),
        ])?;
        self.paged(0x0a43, 0x10, 1 << 2, 0)?;
        self.paged(0x0a43, 0x11, 0, 1 << 4)
    }
    pub(super) fn fp_phy(&self) -> Result<(), BlockError> {
        for &(address, clear, set) in FP_PARAMETERS {
            self.g_parameter(address, clear, set)?;
        }
        self.g_parameter(0x8011, 0, 0x0800)?;
        self.paged(0x0a44, 0x11, 0, 1 << 11)?;
        self.g_parameter(0x8016, 0, 0x0400)?;
        self.paged(0x0a43, 0x10, 1 << 2, 0)?;
        self.paged(0x0a43, 0x11, 0, 1 << 4)?;
        self.paged(0x0a4a, 0x11, 0, 0x0200)?;
        self.paged(0x0a42, 0x14, 0, 0x0080)
    }
}
