/// A `coex_rf_para`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) struct RfLevels {
    /// `bt_pwr_dec_lvl`.
    pub bluetooth_power: u8,
    /// `wl_low_gain_en`.
    pub low_gain: bool,
    /// `bt_lna_lvl`.
    pub bluetooth_lna: u8,
}

const fn rf(bluetooth_power: u8, low_gain: bool, bluetooth_lna: u8) -> RfLevels {
    RfLevels {
        bluetooth_power,
        low_gain,
        bluetooth_lna,
    }
}

