pub(super) unsafe fn sha256(state: *mut u32, blocks: *const u8, count: usize) {
    // SAFETY: the caller checks SHA/SSE controls and the complete extents.
    unsafe { sha256_kernel(state, blocks, count, SHA_CONSTANTS.as_ptr()) };
}

