//! Pointer-only x86 kernels for the soft-float firmware ABI.
#[cfg(target_os = "uefi")]
use core::arch::asm;
use core::arch::naked_asm;
#[cfg(target_os = "uefi")]
use core::arch::x86_64::__cpuid_count;

#[cfg(target_os = "uefi")]
fn sse_usable() -> bool {
    #[cfg(target_os = "uefi")]
    {
        let cr0: u64;
        let cr4: u64;
        // SAFETY: the UEFI mount runs at CPL0. Observe controls only.
        unsafe {
            asm!("mov {}, cr0", out(reg) cr0, options(nomem, nostack, preserves_flags));
            asm!("mov {}, cr4", out(reg) cr4, options(nomem, nostack, preserves_flags));
        }
        cr0 & ((1 << 2) | (1 << 3)) == 0 && cr4 & (1 << 9) != 0
    }
    #[cfg(not(target_os = "uefi"))]
    {
        true
    }
}

#[cfg(not(target_os = "uefi"))]
cpufeatures::new!(aes_host, "aes");
#[cfg(not(target_os = "uefi"))]
cpufeatures::new!(sha_host, "sha", "ssse3", "sse4.1");

pub(super) fn aes_usable() -> bool {
    if cfg!(feature = "force-software") {
        return false;
    }
    #[cfg(not(target_os = "uefi"))]
    return aes_host::get();
    #[cfg(target_os = "uefi")]
    {
        __cpuid_count(1, 0).ecx & (1 << 25) != 0 && sse_usable()
    }
}
pub(super) fn sha_usable() -> bool {
    if cfg!(feature = "force-software") {
        return false;
    }
    #[cfg(not(target_os = "uefi"))]
    return sha_host::get();
    #[cfg(target_os = "uefi")]
    {
        if __cpuid_count(0, 0).eax < 7 {
            return false;
        }
        let ecx = __cpuid_count(1, 0).ecx;
        ecx & ((1 << 9) | (1 << 19)) == (1 << 9) | (1 << 19)
            && __cpuid_count(7, 0).ebx & (1 << 29) != 0
            && sse_usable()
    }
}

