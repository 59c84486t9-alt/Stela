//! Independent original PACE and STKG producer transformations.
//!
//! Entropy generation/initialization remains the boot-policy owner's
//! responsibility. The supplied provenances are claims, not trust receipts.
use super::{Action, Field, Provenance, source_record};
use crate::coprocessor::Staged;
use alloc::vec::Vec;
use anyhow::{Result, ensure};

const PACE: u32 = u32::from_be_bytes(*b"PACE");
const STACK_GUARD: u32 = u32::from_be_bytes(*b"STKG");

/// Outputs of three distinct native generator requests. Neither the decoded
/// PACE seed nor the SLID request substitutes for either supplied output.
/// This input has no Debug/Serialize implementation.
pub struct Input {
    pub pace: [u8; 8],
    pub pace_provenance: Provenance,
    pub stack_guard: Vec<u8>,
    pub stack_guard_choice: u8,
    /// Claim covering both independent STKG outputs (full record and choice).
    pub stack_guard_provenance: Provenance,
}

/// Proposed decisions for the caller's still-required complete patchbay policy.
/// Each applied field keeps its own entropy provenance in the normal receipt.
pub struct Fields {
    pub pace: Field,
    pub stack_guard: Field,
}

impl Staged {
    /// iBoot153de4..153e40 copies an eight-byte generator output to
    /// PACE. Independently,1541cc..154238/15550c fills the entire STKG record
    /// with another generator output, then clears the generated byte at
    /// `random_u8 % record_length` using a third generator request.
    /// This prepares decisions without changing the staged image or its chains.
    pub fn entropy_fields(&self, input: Input) -> Result<Fields> {
        input.pace_provenance.validate()?;
        input.stack_guard_provenance.validate()?;
        let (pace, _) = source_record(self, PACE)?;
        ensure!(pace.bytes == 8, "native PACE record is not eight bytes");
        let (_, original_guard) = source_record(self, STACK_GUARD)?;
        ensure!(
            !original_guard.is_empty(),
            "native STKG mutation requires a nonempty record"
        );
        ensure!(
            input.stack_guard.len() == original_guard.len(),
            "native STKG entropy width disagrees with record"
        );
        let mut guard = input.stack_guard;
        let index = usize::from(input.stack_guard_choice) % guard.len();
        guard[index] = 0;
        Ok(Fields {
            pace: Field {
                tag: PACE,
                action: Action::Replace(input.pace.to_vec()),
                provenance: input.pace_provenance,
            },
            stack_guard: Field {
                tag: STACK_GUARD,
                action: Action::Replace(guard),
                provenance: input.stack_guard_provenance,
            },
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::coprocessor::{
        configuration::tests::{config_policy, provenance},
        tests::{fixture, prepare, w32, w64},
    };
    use stela_formats::sha256;

    fn input(choice: u8) -> Input {
        Input {
            pace: [0xa5; 8],
            pace_provenance: provenance(),
            stack_guard: alloc::vec![0x91, 0x82, 0x73, 0x64],
            stack_guard_choice: choice,
            stack_guard_provenance: provenance(),
        }
    }
    fn original() -> alloc::vec::Vec<u8> {
        let mut b = fixture();
        // Same bounded record layout, independent of the hardware role/source.
        w32(&mut b, 0x1210, STACK_GUARD);
        w32(&mut b, 0x1214, 4);
        w32(&mut b, 0x1218, 0x44332211);
        b
    }

    #[test]
    fn independent_entropy_fields_install_generated_guard_and_preserve_all_chains() -> Result<()> {
        for choice in [0u8, 3, 4, 255] {
            let decoded = original();
            let p = prepare(&decoded)?;
            let mut policy = config_policy(p.plan());
            let staged = p.stage(0x800000, 0x3000)?;
            let hash = sha256(staged.bytes());
            let fields = staged.entropy_fields(input(choice))?;
            assert_eq!(sha256(staged.bytes()), hash);
            for field in [fields.pace, fields.stack_guard] {
                let tag = field.tag;
                *policy.fields.iter_mut().find(|f| f.tag == tag).unwrap() = field;
            }
            let configured = staged.configure(policy)?;
            assert_eq!(&configured.bytes()[0x208..0x210], &[0xa5; 8]);
            let mut expected = [0x91, 0x82, 0x73, 0x64];
            expected[usize::from(choice) % 4] = 0;
            assert_eq!(&configured.bytes()[0x218..0x21c], &expected);
            for fixup in &configured.plan().chains.pointers {
                let at = fixup.image_offset as usize;
                assert_eq!(&configured.bytes()[at..at + 8], &fixup.raw.to_le_bytes());
            }
        }
        Ok(())
    }

    #[test]
    fn native_entropy_requires_both_original_records_and_provenance() -> Result<()> {
        let staged = prepare(&original())?.stage(0x800000, 0x3000)?;
        let mut bad = input(1);
        bad.pace_provenance.coordinates.clear();
        assert!(staged.entropy_fields(bad).is_err());
        let mut bad = input(1);
        bad.stack_guard_provenance.input_sha256.clear();
        assert!(staged.entropy_fields(bad).is_err());
        let mut bad = input(1);
        bad.stack_guard.pop();
        assert!(staged.entropy_fields(bad).is_err());
        assert!(
            prepare(&fixture())?
                .stage(0x800000, 0x3000)?
                .entropy_fields(input(1))
                .is_err()
        );
        let mut b = original();
        // A zero-width STKG remains a legal packed record, but this native
        // producer operation cannot invent a guard byte outside that record.
        w32(&mut b, 0x1214, 0);
        w32(&mut b, 0x1218, 0x62417267);
        w32(&mut b, 0x121c, 5);
        w64(&mut b, 32 + 232 + 40, 37);
        assert!(
            prepare(&b)?
                .stage(0x800000, 0x3000)?
                .entropy_fields(input(1))
                .is_err()
        );
        Ok(())
    }
}
