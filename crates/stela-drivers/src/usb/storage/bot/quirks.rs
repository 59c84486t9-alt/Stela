use super::super::super::xhci::{Device, HIGH_SPEED};
const SINGLE_LUN: u32 = 0x00000001;
const SCM_MULT_TARG: u32 = 0x00000004;
const FIX_INQUIRY: u32 = 0x00000008;
const FIX_CAPACITY: u32 = 0x00000010;
const IGNORE_RESIDUE: u32 = 0x00000020;
const BULK32: u32 = 0x00000040;
const NOT_LOCKABLE: u32 = 0x00000080;
const GO_SLOW: u32 = 0x00000100;
const NO_WP_DETECT: u32 = 0x00000200;
const MAX_SECTORS_64: u32 = 0x00000400;
const IGNORE_DEVICE: u32 = 0x00000800;
const CAPACITY_HEURISTICS: u32 = 0x00001000;
const MAX_SECTORS_MIN: u32 = 0x00002000;
const BULK_IGNORE_TAG: u32 = 0x00004000;
const CAPACITY_OK: u32 = 0x00010000;
const NO_READ_DISC_INFO: u32 = 0x00040000;
const NO_READ_CAPACITY_16: u32 = 0x00080000;
const INITIAL_READ10: u32 = 0x00100000;
const WRITE_CACHE: u32 = 0x00200000;
const NEEDS_CAP16: u32 = 0x00400000;
const BROKEN_FUA: u32 = 0x01000000;
const NO_ATA_1X: u32 = 0x02000000;
const NO_REPORT_LUNS: u32 = 0x10000000;
const ALWAYS_SYNC: u32 = 0x20000000;
const SENSE_AFTER_SYNC: u32 = 0x80000000;

#[derive(Clone, Copy, Debug, Default)]
pub(super) struct Flags(u32);
impl Flags {
    pub fn from_device(device: &Device) -> Result<Self, &'static str> {
        let d = &device.descriptor;
        Self::from_id(
            u16::from_le_bytes([d[8], d[9]]),
            u16::from_le_bytes([d[10], d[11]]),
            u16::from_le_bytes([d[12], d[13]]),
            device.speed == HIGH_SPEED,
        )
    }
    pub(super) fn from_id(
        vendor: u16,
        product: u16,
        revision: u16,
        high_speed: bool,
    ) -> Result<Self, &'static str> {
        let found = DEVICES.iter().find(|&&(v, p, lo, hi, _, _)| {
            v == vendor && p == product && (lo..=hi).contains(&revision)
        });
        let mut bits = if let Some(&(_, _, _, _, bits, unsupported)) = found {
            if unsupported || bits & (IGNORE_DEVICE | SCM_MULT_TARG | FIX_INQUIRY) != 0 {
                return Err(
                    "USB BOT profile requires unsupported initialization, transport or fabricated inquiry",
                );
            }
            bits
        } else {
            0
        };
        if !high_speed {
            bits &= !GO_SLOW;
        }
        // scsiglue enables the odd-capacity heuristic for these flash vendors.
        if matches!(vendor, 0x0421 | 0x04b0 | 0x0a17 | 0x22b8)
            && bits & (FIX_CAPACITY | CAPACITY_OK) == 0
        {
            bits |= CAPACITY_HEURISTICS;
        }
        Ok(Self(bits))
    }
    pub fn single_lun(self) -> bool {
        self.0 & SINGLE_LUN != 0
    }
    pub fn cbw_len(self) -> usize {
        if self.0 & BULK32 != 0 { 32 } else { 31 }
    }
    pub fn go_slow(self) -> bool {
        self.0 & GO_SLOW != 0
    }
    pub fn ignore_tag(self) -> bool {
        self.0 & BULK_IGNORE_TAG != 0
    }
    pub fn ignore_residue(self) -> bool {
        self.0 & IGNORE_RESIDUE != 0
    }
    pub fn learn_residue(&mut self) {
        self.0 |= IGNORE_RESIDUE;
    }
    pub fn write_protect(self) -> bool {
        self.0 & (NO_WP_DETECT | ALWAYS_SYNC) == 0
    }
    pub fn write_cache(self) -> bool {
        self.0 & (WRITE_CACHE | ALWAYS_SYNC) != 0
    }
    pub fn capacity16_first(self) -> bool {
        self.0 & NEEDS_CAP16 != 0
    }
    pub fn capacity(self, blocks: u64) -> Option<u64> {
        if self.0 & FIX_CAPACITY != 0 || self.0 & CAPACITY_HEURISTICS != 0 && blocks & 1 != 0 {
            blocks.checked_sub(1).filter(|&n| n != 0)
        } else {
            Some(blocks)
        }
    }
    pub fn max_transfer_bytes(self) -> usize {
        if self.0 & MAX_SECTORS_MIN != 0 {
            4096
        } else if self.0 & MAX_SECTORS_64 != 0 {
            32768
        } else {
            super::MAX_TD
        }
    }
    pub fn initial_read(self) -> bool {
        self.0 & INITIAL_READ10 != 0
    }
    pub fn sense_after_sync(self) -> bool {
        self.0 & SENSE_AFTER_SYNC != 0
    }
    pub fn permits(self, cdb: &[u8]) -> bool {
        let Some(&op) = cdb.first() else {
            return false;
        };
        // BOT disks never expose WRITE SAME or REPORT SUPPORTED OPCODES; the
        // physical bridge restrictions also apply to raw commands.
        !(matches!(op, 0x41 | 0x93 | 0x7f | 0x53)
            || op == 0xa3 && cdb.get(1).is_none_or(|b| b & 31 == 12)
            || self.0 & NOT_LOCKABLE != 0 && op == 0x1e
            || self.0 & NEEDS_CAP16 != 0 && op == 0x25
            || self.0 & NO_READ_DISC_INFO != 0 && op == 0x51
            || self.0 & NO_ATA_1X != 0 && matches!(op, 0x85 | 0xa1)
            || self.0 & NO_REPORT_LUNS != 0 && op == 0xa0
            || self.0 & NO_READ_CAPACITY_16 != 0
                && op == 0x9e
                && cdb.get(1).is_none_or(|b| b & 31 == 16)
            || self.0 & BROKEN_FUA != 0
                && matches!(
                    op,
                    0x28 | 0x2a | 0x2e | 0xa8 | 0xaa | 0xae | 0x88 | 0x89 | 0x8a | 0x8e | 0x9c
                )
                && cdb.get(1).is_none_or(|b| b & 8 != 0))
    }
}
