#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn complete_guarded_family_preserves_order_masks_and_unqualified_identity() {
        let p = Profile::new(0x6000, 8, 0).unwrap();
        assert_eq!(
            (0..193)
                .map(|id| p.program(id).unwrap().len())
                .sum::<usize>(),
            3299
        );
        assert_eq!(p.program(0).unwrap()[0], t(0, 3, 1));
        assert_eq!(p.program(0).unwrap()[0].apply(0xffff_fffe), 0xffff_fffd);
        assert!(p.program(7).unwrap().is_empty());
        for id in 128..193 {
            assert!(p.program(id).unwrap().is_empty());
        }
        assert!(p.program(193).is_err());
        for (chip, board, revision) in [(0x6001, 8, 0), (0x6000, 10, 0), (0x6000, 8, 0x10)] {
            assert!(Profile::new(chip, board, revision).is_err());
        }
        for id in 0..193 {
            let rows = p.program(id).unwrap();
            let fields = p.fields(id).unwrap();
            for row in rows {
                assert_eq!(row.offset % 4, 0);
                assert_eq!(row.value & !row.mask, 0);
                assert!(
                    fields.contains(&(
                        u64::from(row.offset),
                        rows.iter()
                            .filter(|r| r.offset == row.offset)
                            .fold(0, |m, r| m | r.mask)
                    ))
                );
            }
        }
    }
}
