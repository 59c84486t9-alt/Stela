//! Lazy resolution of registered leaf entry points. Handles must be revalidated
//! before each execution; invalidation does not interrupt running code.

use crate::{Identity, Prepared, prepare_leaf};
use alloc::collections::BTreeMap;
use alloc::sync::Arc;
#[cfg(not(feature = "std"))]
use alloc::{string::String, vec::Vec};
use anyhow::{Result, ensure};
use std::path::PathBuf;
use stela_compiler::GuestAddress;
use stela_core::sha256;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DispatchIdentity {
    pub address_space: u64,
    pub mapping_generation: u64,
    pub translation: Identity,
}

/// A generated leaf and its registration identity.
#[derive(Debug, Clone)]
pub struct ResolvedLeaf {
    identity: DispatchIdentity,
    prepared: Arc<Prepared>,
    issuer: Arc<()>,
}

impl ResolvedLeaf {
    pub fn identity(&self) -> &DispatchIdentity {
        &self.identity
    }

    pub fn prepared(&self) -> &Prepared {
        &self.prepared
    }

    /// Associate an offset within generated bytes with its guest instruction.
    /// This does not reconstruct intermediate state or deliver a guest fault.
    pub fn guest_instruction_for_native_offset(&self, offset: usize) -> Option<GuestAddress> {
        let manifest = &self.prepared.manifest;
        if offset >= manifest.native_bytes {
            return None;
        }
        let index = manifest
            .source_map
            .partition_point(|(_, start)| *start <= offset);
        index.checked_sub(1).map(|i| manifest.source_map[i].0)
    }
}

#[derive(Debug)]
struct RegisteredLeaf {
    source: Vec<u8>,
    source_sha256: String,
    end: u64,
    generation: u64,
}

/// Process-local registration and lookup of leaf regions. Each registry also
/// has a private issuer identity, so handles from one never validate in
/// another.
#[derive(Debug)]
pub struct LeafDispatcher {
    address_space: u64,
    cache_root: PathBuf,
    next_generation: u64,
    leaves: BTreeMap<u64, RegisteredLeaf>,
    issuer: Arc<()>,
}

impl LeafDispatcher {
    pub fn new(address_space: u64, cache_root: PathBuf) -> Self {
        Self {
            address_space,
            cache_root,
            next_generation: 0,
            leaves: BTreeMap::new(),
            issuer: Arc::new(()),
        }
    }

    /// Register immutable source bytes; replacing an entry always gives it a
    /// fresh generation, including replacement with byte-identical source.
    /// Unsupported semantics fail later during resolve, without creating code.
    pub fn register(&mut self, entry: GuestAddress, source: Vec<u8>) -> Result<u64> {
        ensure!(
            !source.is_empty() && source.len().is_multiple_of(4) && entry.0.is_multiple_of(4),
            "leaf source and entry must be nonempty and 4-byte aligned"
        );
        let length = u64::try_from(source.len())?;
        let end = entry
            .0
            .checked_add(length)
            .ok_or_else(|| anyhow::anyhow!("leaf range overflow"))?;
        for (&base, leaf) in &self.leaves {
            ensure!(
                base == entry.0 || end <= base || entry.0 >= leaf.end,
                "leaf registration overlaps another registered region"
            );
        }
        let generation = self
            .next_generation
            .checked_add(1)
            .ok_or_else(|| anyhow::anyhow!("mapping generation exhausted"))?;
        let source_sha256 = sha256(&source);
        self.leaves.insert(
            entry.0,
            RegisteredLeaf {
                source,
                source_sha256,
                end,
                generation,
            },
        );
        self.next_generation = generation;
        Ok(generation)
    }

    pub fn unregister(&mut self, entry: GuestAddress) -> bool {
        self.leaves.remove(&entry.0).is_some()
    }

    /// Resolve a registered entry only; interior addresses are not entries.
    /// Persisted checksums are revalidated on every lookup, including disk
    /// hits.
    pub fn resolve(&self, entry: GuestAddress) -> Result<ResolvedLeaf> {
        let leaf = self
            .leaves
            .get(&entry.0)
            .ok_or_else(|| anyhow::anyhow!("unregistered guest entry {:#x}", entry.0))?;
        let prepared = prepare_leaf(&leaf.source, entry, &self.cache_root)?;
        ensure!(
            prepared.manifest.identity.source_sha256 == leaf.source_sha256,
            "registered source identity mismatch"
        );
        validate_source_map(&prepared, entry, leaf.source.len())?;
        Ok(ResolvedLeaf {
            identity: DispatchIdentity {
                address_space: self.address_space,
                mapping_generation: leaf.generation,
                translation: prepared.manifest.identity.clone(),
            },
            prepared: Arc::new(prepared),
            issuer: self.issuer.clone(),
        })
    }

    /// A stale handle remains inspectable, but must not become a live target.
    /// This check is serialized with registry updates via the borrow rules; a
    /// future multi-thread executor needs a separate execution/lifetime guard.
    pub fn is_current(&self, resolved: &ResolvedLeaf) -> bool {
        if !Arc::ptr_eq(&self.issuer, &resolved.issuer)
            || self.address_space != resolved.identity.address_space
        {
            return false;
        }
        let identity = &resolved.identity.translation;
        self.leaves.get(&identity.guest_base).is_some_and(|leaf| {
            leaf.generation == resolved.identity.mapping_generation
                && leaf.source_sha256 == identity.source_sha256
        })
    }
}

fn validate_source_map(
    prepared: &Prepared,
    entry: GuestAddress,
    source_bytes: usize,
) -> Result<()> {
    let manifest = &prepared.manifest;
    ensure!(
        !manifest.verified,
        "generated cache is not verification evidence"
    );
    ensure!(manifest.native_bytes > 0, "empty generated code");
    ensure!(
        manifest.source_map.len() == source_bytes / 4,
        "source map must cover every registered guest instruction"
    );
    let mut previous = None;
    for (index, &(guest, native)) in manifest.source_map.iter().enumerate() {
        let expected = entry
            .0
            .checked_add((index as u64) * 4)
            .ok_or_else(|| anyhow::anyhow!("source map guest address overflow"))?;
        ensure!(guest.0 == expected, "source map guest instruction mismatch");
        ensure!(
            native < manifest.native_bytes,
            "source map offset outside generated code"
        );
        ensure!(
            previous.is_none_or(|p| native > p),
            "source map offsets must increase strictly"
        );
        ensure!(
            index != 0 || native == 0,
            "source map must start at native offset zero"
        );
        previous = Some(native);
    }
    Ok(())
}

