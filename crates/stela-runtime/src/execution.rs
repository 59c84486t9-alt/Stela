// Bounds a cached artifact so it cannot force an unbounded allocation or
// mapping.
pub(crate) const MAX_NATIVE_BYTES: usize = 64 * 1024 * 1024;

/// An owned RX copy of one registered leaf's code. It is neither Send nor Sync.
#[cfg(feature = "std")]
#[derive(Debug)]
pub struct ExecutableLeaf {
    resolved: ResolvedLeaf,
    mapping: platform::Mapping,
    _serialized: PhantomData<Rc<()>>,
}

#[cfg(feature = "std")]
impl ExecutableLeaf {
    /// Read and hash generated bytes against the immutable resolved manifest,
    /// check the current compiler/ABI/CPU identity, and create an RX mapping.
    ///
    /// The persisted manifest is not reread: external cache edits cannot change
    /// the identity or expected hash held by the resolved handle. An already
    /// loaded mapping remains independent of later disk changes.
    pub fn load(dispatcher: &LeafDispatcher, resolved: &ResolvedLeaf) -> Result<Self> {
        ensure!(
            dispatcher.is_current(resolved),
            "stale or foreign registered leaf"
        );
        let manifest = &resolved.prepared().manifest;
        let identity = &manifest.identity;
        ensure!(
            *identity == resolved.identity().translation,
            "resolved translation identity mismatch"
        );
        ensure!(
            identity.schema_version == 1,
            "unsupported translation schema"
        );
        ensure!(
            identity.compiler_source_sha256 == crate::compiler_source_sha256(),
            "generated code uses a different compiler"
        );
        ensure!(identity.abi == NATIVE_ABI, "unsupported generated-code ABI");
        let target = identity
            .target_cpu
            .parse::<stela_compiler::TargetCpu>()
            .map_err(anyhow::Error::msg)?;
        ensure!(
            crate::platform::cpu::admitted(target),
            "host CPU lacks generated-code requirements {}",
            target.id()
        );
        ensure!(
            !manifest.verified,
            "cache metadata is not verification evidence"
        );
        ensure!(
            manifest.native_bytes > 0 && manifest.native_bytes <= MAX_NATIVE_BYTES,
            "generated-code size exceeds execution bound"
        );
        platform::ensure_supported()?;
        let path = resolved.prepared().directory.join("native.bin");
        let mut bytes = Vec::new();
        std::fs::File::open(&path)
            .with_context(|| format!("open generated artifact {}", path.display()))?
            .take((MAX_NATIVE_BYTES + 1) as u64)
            .read_to_end(&mut bytes)?;
        ensure!(
            bytes.len() == manifest.native_bytes && sha256(&bytes) == manifest.native_sha256,
            "generated artifact differs from resolved immutable manifest"
        );
        let mapping = platform::Mapping::new(&bytes)?;
        // The immutable dispatcher borrow spans validation and publication.
        ensure!(
            dispatcher.is_current(resolved),
            "registered leaf became stale"
        );
        Ok(Self {
            resolved: resolved.clone(),
            mapping,
            _serialized: PhantomData,
        })
    }

    pub fn resolved(&self) -> &ResolvedLeaf {
        &self.resolved
    }

    pub fn native_bytes(&self) -> usize {
        self.resolved.prepared().manifest.native_bytes
    }

    /// Execute this leaf against the ABI's memory-backed guest register state.
    /// Registration is checked immediately before the native call, while this
    /// immutable dispatcher borrow excludes serialized replacement/removal.
    ///
    /// # Safety
    ///
    /// The caller must trust the registered source and generated bytes, and must
    /// establish that this leaf returns in finite time. Every executed guest
    /// load/store must address live ordinary RAM at the identical native virtual
    /// address, with sufficient bounds, permissions and alignment for the direct
    /// RAM profile. RAM must remain live for the entire call. Guest memory cannot
    /// alias `state`, executable bytes, this object, the dispatcher, any live Rust
    /// references, or host metadata/stack. Guest writes require exclusive access
    /// and cannot race other threads. SP-based accesses must satisfy the enabled
    /// ARM alignment checks. No MMIO, PAC/tagged-pointer assumptions, atomicity,
    /// concurrent code mutation, external calls or guest exception delivery are
    /// supported. A guest fault can terminate the host process; this API does not
    /// install a signal handler or sandbox untrusted code.
    pub unsafe fn execute(
        &self,
        dispatcher: &LeafDispatcher,
        state: &mut GuestState,
    ) -> Result<()> {
        ensure!(
            dispatcher.is_current(&self.resolved),
            "refusing stale or foreign native execution"
        );
        // SAFETY: the caller upholds the direct-RAM and termination contract;
        // the mapping is owned, immutable RX with the checked ABI.
        unsafe { self.mapping.call(state) }
    }
}

#[cfg(all(target_arch = "x86_64", any(target_os = "macos", target_os = "linux")))]
pub(crate) mod platform {
    use super::native_image::{ExecutableStorage, NativeImage};
    use anyhow::{Context, Result, ensure};
    use core::{convert::Infallible, ptr::NonNull};
    use stela_compiler::GuestState;

    pub(crate) type StorageError = Infallible;

    pub fn ensure_supported() -> Result<()> {
        // Every x86-64 CPU implements Stela's integer and SSE2 baseline.
        // Mac x86-64 and Linux x86-64 both use the required System V C ABI.
        Ok(())
    }

    #[derive(Debug)]
    pub struct Mapping {
        pointer: NonNull<u8>,
        length: usize,
    }

    impl Mapping {
        pub fn new(bytes: &[u8]) -> Result<Self> {
            ensure!(!bytes.is_empty(), "cannot map empty native code");
            // SAFETY: Request fresh anonymous private RW storage. MAP_FAILED is
            // checked before the pointer is used. Never request executable RW.
            let pointer = unsafe {
                libc::mmap(
                    core::ptr::null_mut(),
                    bytes.len(),
                    libc::PROT_READ | libc::PROT_WRITE,
                    libc::MAP_PRIVATE | libc::MAP_ANON,
                    -1,
                    0,
                )
            };
            if pointer == libc::MAP_FAILED {
                return Err(std::io::Error::last_os_error()).context("allocate RW native code");
            }
            let Some(pointer) = NonNull::new(pointer.cast::<u8>()) else {
                // Address zero cannot back a Rust NonNull mapping, even if an OS
                // were to honor it. Release the successful OS allocation first.
                unsafe { libc::munmap(pointer, bytes.len()) };
                anyhow::bail!("OS returned an unusable null native mapping");
            };
            let mapping = Self {
                pointer,
                length: bytes.len(),
            };
            // SAFETY: mmap returned at least length fresh RW bytes, disjoint from
            // the input Vec, and this mapping has not escaped.
            unsafe {
                core::ptr::copy_nonoverlapping(
                    bytes.as_ptr(),
                    mapping.pointer.as_ptr(),
                    bytes.len(),
                );
            }
            // SAFETY: the whole mapping is initialized. The OS switches it from
            // RW to RX atomically, and x86 instruction and data caches are
            // coherent.
            let result = unsafe {
                libc::mprotect(
                    mapping.pointer.as_ptr().cast(),
                    mapping.length,
                    libc::PROT_READ | libc::PROT_EXEC,
                )
            };
            if result != 0 {
                // mapping's Drop releases memory on this error path too.
                return Err(std::io::Error::last_os_error()).context("protect native code RX");
            }
            Ok(mapping)
        }

        pub unsafe fn call(&self, state: &mut GuestState) -> Result<()> {
            // SAFETY: the mapping is still owned and the caller upholds the
            // leaf ABI.
            let reached = match unsafe { NativeImage::borrow(self).call(state) } {
                Ok(reached) => reached,
                Err(never) => match never {},
            };
            reached.into_infallible();
            Ok(())
        }

        pub unsafe fn call_context_block(
            &self,
            state: &mut GuestState,
            context: &mut stela_compiler::context::ExecutionContext,
        ) -> Result<stela_compiler::block::BlockExit> {
            // SAFETY: the mapping and the block's context stay borrowed for
            // this synchronous call.
            let reached = match unsafe { self.call_context_block_observed(state, context) } {
                Ok(reached) => reached,
                Err(never) => match never {},
            };
            Ok(reached.into_infallible())
        }

        /// Call the two-argument context-leaf ABI. Architectural failures are
        /// recorded in the memory view, never inferred from RAX.
        pub unsafe fn call_context(
            &self,
            state: &mut GuestState,
            context: &mut stela_compiler::context::ExecutionContext,
        ) -> Result<()> {
            // SAFETY: The context entry owns the checked source/profile and
            // validates its live borrowed views before this synchronous call.
            let function: unsafe extern "C" fn(
                *mut GuestState,
                *mut stela_compiler::context::ExecutionContext,
            ) = unsafe { core::mem::transmute(self.pointer.as_ptr()) };
            unsafe { function(state, context) };
            Ok(())
        }

        /// Keep the native result alongside the storage check. Err is a refusal
        /// before the call; hosted storage cannot fail.
        ///
        /// # Safety
        /// The source, native code, ABI, map, requirements and context must be
        /// bound. A PE may call only from its session, which holds the thread,
        /// system state, backend, source and domain through this call, the
        /// context finalization and PC settlement.
        pub(crate) unsafe fn call_context_block_observed(
            &self,
            state: &mut GuestState,
            context: &mut stela_compiler::context::ExecutionContext,
        ) -> core::result::Result<
            super::ObservedNativeCall<stela_compiler::block::BlockExit, Infallible>,
            Infallible,
        > {
            // SAFETY: the mapping stays borrowed, and the caller upholds the
            // execution contract.
            unsafe { NativeImage::borrow(self).call_context_block(state, context) }
        }

        /// Call the resident-budget block ABI. The budget bounds execution.
        ///
        /// # Safety
        /// The caller binds the source, ABI, target and register bank. Resident
        /// loops are non-faulting integer code; a fallback has the ordinary
        /// call's memory, fault and target requirements. Not for asynchronous
        /// producer domains or checked, system or threaded entry.
        pub unsafe fn call_budgeted_block(
            &self,
            state: &mut GuestState,
            budget: &mut stela_compiler::block::loop_budget::LoopBudget,
        ) -> Result<stela_compiler::block::BlockExit> {
            // SAFETY: the mapping, register bank and budget stay borrowed
            // through the call.
            let reached =
                match unsafe { NativeImage::borrow(self).call_budgeted_block(state, budget) } {
                    Ok(reached) => reached,
                    Err(never) => match never {},
                };
            Ok(reached.into_infallible())
        }

        /// The native result and storage check for the one-pointer block ABI.
        /// The PE's session must hold its state, source and domain through
        /// settlement.
        pub(crate) unsafe fn call_block_observed(
            &self,
            state: &mut GuestState,
        ) -> core::result::Result<
            super::ObservedNativeCall<stela_compiler::block::BlockExit, Infallible>,
            Infallible,
        > {
            // SAFETY: the caller upholds the source, profile, ABI and map, and
            // the session contract.
            unsafe { NativeImage::borrow(self).call_block(state) }
        }

        pub unsafe fn call_block(
            &self,
            state: &mut GuestState,
        ) -> Result<stela_compiler::block::BlockExit> {
            // SAFETY: the caller upholds the struct-return ABI and the
            // direct-RAM contract.
            let reached = match unsafe { self.call_block_observed(state) } {
                Ok(reached) => reached,
                Err(never) => match never {},
            };
            Ok(reached.into_infallible())
        }

        #[cfg(test)]
        pub fn address(&self) -> usize {
            self.pointer.as_ptr() as usize
        }
    }

    // SAFETY: Mapping::new exclusively owns fresh initialized mmap storage,
    // atomically transitioned to RX. Its pointer never escapes. All calls borrow
    // self; no unmap or writable alias can coexist through safe runtime APIs.
    // Host ownership is infallible to retain, so no fallible frame postcheck is
    // invented for this implementation. Guest ABI/PE admission stays at callsite.
    unsafe impl ExecutableStorage for Mapping {
        type Error = Infallible;
        fn entry(&self) -> NonNull<u8> {
            self.pointer
        }
        fn revalidate(&self) -> core::result::Result<(), Self::Error> {
            Ok(())
        }
    }

    impl Drop for Mapping {
        fn drop(&mut self) {
            // SAFETY: the mapping is uniquely owned and no pointer into it
            // escapes; calls borrow `self`, so none outlives Drop.
            unsafe { libc::munmap(self.pointer.as_ptr().cast(), self.length) };
        }
    }
}

