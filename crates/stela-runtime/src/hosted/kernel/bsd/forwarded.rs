const FAMILIES: &[&[&str]] = &[
    FILES,
    NETWORK,
    IDENTITY,
    INFORMATION,
    SYNCHRONIZATION,
    MEMORY,
];

pub(super) fn forwarded(name: &str) -> bool {
    FAMILIES.iter().any(|family| family.contains(&name))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::darwin::catalog;

    #[test]
    fn every_forwarded_call_is_an_implemented_catalog_row_once() {
        let mut seen = std::collections::BTreeSet::new();
        for name in FAMILIES.iter().flat_map(|family| family.iter()) {
            assert!(seen.insert(*name), "{name} is listed twice");
            let row = (0..=u16::MAX)
                .map_while(catalog::entry)
                .find(|entry| entry.name == *name)
                .unwrap_or_else(|| panic!("{name} is not in the catalog"));
            assert!(row.prototype().is_some(), "{name} is reserved");
        }
    }
}
