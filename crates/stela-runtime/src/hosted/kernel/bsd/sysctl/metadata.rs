//! The declared ARM Darwin sysctl namespace: public kind/format/description
//! facts from the unchanged 26A434 kernel's startup OID registrations,
//! checked against pinned XNU kern_mib.c, kern_sysctl.c and arm64/sysctl.c.
//! Complete descriptor/parent/startup coordinates stay in the ignored r11
//! source ledger. No kernel pointers, image bytes or content values are used.
//!
//! NOAUTO cputhreadtype is not registered on these non-SMT ARM profiles
//! (cpu_threadtype == CPU_THREADTYPE_NONE); debug-only declarations and
//! later driver registrations are not part of this static publication.

pub(super) const TYPE_MASK: u32 = 15;
pub(super) const NODE: u32 = 1;
pub(super) const WRITE: u32 = 0x4000_0000;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct Info {
    pub(super) flags: u32,
    pub(super) format: &'static str,
    pub(super) description: &'static str,
}

impl Info {
    pub(super) fn node(self) -> bool {
        self.flags & TYPE_MASK == NODE
    }
    pub(super) fn read_only(mut self) -> Self {
        self.flags &= !WRITE;
        self
    }
}

pub(super) type Declaration = (&'static str, u32, &'static str, &'static str);

pub(super) fn info(name: &str) -> Option<Info> {
    DECLARATIONS
        .iter()
        .find(|entry| entry.0 == name)
        .map(|entry| Info {
            flags: entry.1,
            format: entry.2,
            description: entry.3,
        })
}

