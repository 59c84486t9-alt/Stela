#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn source_publication_is_unique_and_every_parent_is_a_branch() {
        assert_eq!(DECLARATIONS.len(), 260);
        let mut previous = "";
        for &(name, flags, format, _) in DECLARATIONS {
            assert!(name > previous, "sorted unique: {name}");
            previous = name;
            assert!((1..=5).contains(&(flags & TYPE_MASK)), "{name}");
            assert_eq!(flags & 0x0200_0000, 0, "NOAUTO: {name}");
            if let Some((parent, _)) = name.rsplit_once('.') {
                assert!(info(parent).is_some_and(Info::node), "{name}");
            }
            assert_eq!(format == "N", flags & TYPE_MASK == NODE, "{name}");
        }
    }
}
