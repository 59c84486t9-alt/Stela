//! Source-derived T6000 bridge tuning under explicitly qualified platform guards.
//! Original J314s26A434 constructor supplies chip6000, board8, revision0.
//! These ordered masks/values describe native software's RMW operands. They
//! establish neither physical reset values nor electrical/counter completion.
use alloc::{collections::BTreeMap, vec::Vec};

/// The immutable identity facts used by native tuning guards. Other facts
/// remain explicit requirements until their complete source paths qualify.
#[derive(Debug, Clone, Copy)]
pub struct Profile(());
impl Profile {
    pub fn new(chip: u32, board: u32, revision: u32) -> Result<Self, &'static str> {
        if (chip, board, revision) != (0x6000, 8, 0) {
            return Err("T6000 bridge chip/board/revision tuning guards are not qualified");
        }
        Ok(Self(()))
    }
    pub fn program(self, bridge: usize) -> Result<&'static [Tuning], &'static str> {
        let program = *SELECTED
            .get(bridge)
            .ok_or("T6000 bridge tuning ID is outside the native family")?;
        Ok(PROGRAMS[usize::from(program)])
    }
    pub fn fields(self, bridge: usize) -> Result<Vec<(u64, u32)>, &'static str> {
        let mut fields = BTreeMap::new();
        for row in self.program(bridge)? {
            *fields.entry(u64::from(row.offset)).or_default() |= row.mask;
        }
        Ok(fields.into_iter().collect())
    }
}

/// Original bridge-settings-v1 tuning selection. A set optional-mask bit
/// skips `_configureBridge`'s call to the native tuning helper. It does not
/// remove the physical bank, waive consumers or define its current contents.
pub struct Selection<'a> {
    profile: Profile,
    optional_mask: &'a [u8],
}
impl<'a> Selection<'a> {
    pub fn new(profile: Profile, optional_mask: &'a [u8]) -> Result<Self, &'static str> {
        if optional_mask.len() < super::BRIDGE_COUNT.div_ceil(8) {
            return Err("T6000 optional bridge mask does not cover every actual bridge");
        }
        Ok(Self {
            profile,
            optional_mask,
        })
    }
    pub fn program(&self, bridge: usize) -> Result<&'static [Tuning], &'static str> {
        let program = self.profile.program(bridge)?;
        if self.optional_mask[bridge / 8] & (1 << (bridge % 8)) != 0 {
            Ok(&[])
        } else {
            Ok(program)
        }
    }
}

/// One actual full32 native RMW. Its input must be a real known register
/// value; `apply` does not authorize a read or supply an unknown value.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tuning {
    pub offset: u32,
    pub mask: u32,
    pub value: u32,
}
impl Tuning {
    pub const fn apply(self, current: u32) -> u32 {
        (current & !self.mask) | (self.value & self.mask)
    }
}
const fn t(offset: u32, mask: u32, value: u32) -> Tuning {
    Tuning {
        offset,
        mask,
        value,
    }
}

