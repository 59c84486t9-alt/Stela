//! Public system keys and standalone references through AKS command 0x22.
//!
//! 26A434 kernel file 0x2d41f50: variant 0, session, handle, operation,
//! blob; reply variant 0 and one raw result blob. The public system-key
//! wrapper uses handle -1, operation 2 (constant at 0x725890); the userspace
//! perform-operation dispatch sets operation 0 (0x2d36078). Its DER
//! dictionary is a SET of SEQUENCE { UTF8 key, value } pairs in ascending
//! key order, as the 26A434 restore ramdisk sends it (`o`, `skg`, `skt`),
//! not DER's encoded-pair order. `o=oskgp`, `skt=1`, `skg=1` requests the SIK.
//!
//! P-256 is Stela's system-identity policy, not a recovered Apple hardware
//! KDF or an Apple-certified identity. The private scalar is derived
//! from provisioned machine roots, kept only here and zeroized on drop.
//! Key rotation and other key types are separate unsupported operations.
use super::{
    super::der::{self, Cursor},
    Fields,
    reference_key::{self, ReferenceKey},
};
use crate::Result;
use alloc::{format, string::String};
use hmac::{Hmac, Mac};
use p256::{SecretKey, elliptic_curve::sec1::ToEncodedPoint};
use stela_contracts::refuse;
use stela_crypto::Sha256;
use zeroize::Zeroizing;

pub(super) const PERFORM_OPERATION: u8 = 0x22;
/// Decoding the AP format does not check the security semantics of creation.
pub(super) enum Operation<'a> {
    PublicIdentity,
    CreateReference {
        kind: u32,
    },
    AttestReference {
        blob: &'a [u8],
    },
    SignReference {
        blob: &'a [u8],
        digest: &'a [u8; 32],
    },
}

#[derive(PartialEq, Eq)]
enum ParameterOperation {
    PublicIdentity,
    CreateReference,
    AttestReference,
    SignReference,
}
const PUBLIC_HANDLE: u32 = u32::MAX;
const PUBLIC_OPERATIONS: [u32; 2] = [0, 2];
const IDENTITY_TYPE: u32 = 1;
const IDENTITY_GENERATION: u32 = 1;
const SCALAR_DOMAIN: &[u8] = b"Stela SEP system identity P-256 v1\0";
const MAX_SCALAR_ATTEMPTS: u32 = 256;
const PUBLIC_BYTES: usize = 65;

pub(super) enum PublicQuery {
    Identity,
}

pub(super) struct SystemKeys {
    root: Zeroizing<[u8; 32]>,
    identity: Option<(SecretKey, [u8; PUBLIC_BYTES])>,
}

impl SystemKeys {
    pub(super) fn new(root: Zeroizing<[u8; 32]>) -> Self {
        Self {
            root,
            identity: None,
        }
    }

    pub(super) fn perform(
        &mut self,
        operation: Operation<'_>,
        entropy: &mut dyn super::super::Entropy,
    ) -> Result<alloc::vec::Vec<u8>> {
        match operation {
            Operation::PublicIdentity => Ok(self.public(PublicQuery::Identity)?.to_vec()),
            Operation::CreateReference { kind } => ReferenceKey::create(&self.root, kind, entropy),
            Operation::SignReference { blob, digest } => {
                let reference = ReferenceKey::open(&self.root, blob)?;
                reference.sign_digest(digest)
            }
            Operation::AttestReference { blob } => {
                // Authenticate the complete key reference before using the
                // SIK. This attests only a reference generated by this root.
                let reference = ReferenceKey::open(&self.root, blob)?;
                self.public(PublicQuery::Identity)?;
                let identity = &self.identity.as_ref().unwrap().0;
                let signing = p256::ecdsa::SigningKey::from(identity);
                use p256::ecdsa::signature::Signer;
                // Stela policy: ECDSA/SHA-256 over the uncompressed
                // reference public key, deterministic RFC6979 nonce, DER
                // signature output. No factory certificate or fuse/firmware
                // assertion is created. Apple server format/trust acceptance
                // is distinct from this key-to-key signature.
                let signature: p256::ecdsa::Signature = signing
                    .try_sign(&reference.public())
                    .map_err(|_| refuse!("SEP SIK reference signature failed"))?;
                Ok(signature.to_der().as_bytes().to_vec())
            }
        }
    }

    pub(super) fn public(&mut self, query: PublicQuery) -> Result<&[u8]> {
        match query {
            PublicQuery::Identity => {
                if self.identity.is_none() {
                    let secret = identity_secret(&self.root)?;
                    let point = secret.public_key().to_encoded_point(false);
                    let mut public = [0; PUBLIC_BYTES];
                    public.copy_from_slice(point.as_bytes());
                    self.identity = Some((secret, public));
                }
                Ok(&self.identity.as_ref().unwrap().1)
            }
        }
    }
}

fn identity_secret(root: &[u8; 32]) -> Result<SecretKey> {
    // Rejection sampling preserves the scalar distribution, unlike reducing
    // a 256-bit digest modulo the curve order. The counter changes only on
    // an out-of-range candidate, so reopen reconstructs the identical key.
    for counter in 0..MAX_SCALAR_ATTEMPTS {
        let mut mac = Hmac::<Sha256>::new_from_slice(root).expect("HMAC accepts 256-bit roots");
        mac.update(SCALAR_DOMAIN);
        mac.update(&IDENTITY_TYPE.to_be_bytes());
        mac.update(&IDENTITY_GENERATION.to_be_bytes());
        mac.update(&counter.to_be_bytes());
        let candidate = Zeroizing::new(<[u8; 32]>::from(mac.finalize().into_bytes()));
        if let Ok(secret) = SecretKey::from_slice(candidate.as_ref()) {
            return Ok(secret);
        }
    }
    Err(refuse!("SEP system identity scalar derivation exhausted"))
}

pub(super) fn operation<'a>(variant: u32, fields: &mut Fields<'a>) -> Result<Operation<'a>> {
    if variant != 0 {
        return Err(refuse!("SEP perform-operation variant is not implemented"));
    }
    // The session is caller context. Public queries and creation of a new
    // standalone reference grant no access to an existing credential bag.
    let _session = fields.lword()?;
    let handle = fields.word()?;
    let transport_operation = fields.word()?;
    if handle != PUBLIC_HANDLE || !PUBLIC_OPERATIONS.contains(&transport_operation) {
        return Err(refuse!(
            "SEP perform-operation handle or operation is not implemented"
        ));
    }
    let bytes = fields.blob()?;
    fields.end()?;
    let mut outer = Cursor(bytes);
    let set = outer.take(17)?;
    outer.end()?;
    let mut pairs = Cursor(set.value);
    let mut previous: Option<&[u8]> = None;
    let (mut operation, mut key_type, mut generation) = (None, false, false);
    let (mut reference_class, mut reference_type, mut reference_options) = (None, None, None);
    let mut reference_blob = None;
    let mut digest = None;
    while !pairs.0.is_empty() {
        let mut entry = Cursor(pairs.take(16)?.value);
        let key = entry.take(12)?.value;
        if previous.is_some_and(|p| p >= key) {
            return Err(refuse!(
                "SEP system-key dictionary is duplicated or not key sorted"
            ));
        }
        previous = Some(key);
        match key {
            b"o" => {
                operation = Some(match entry.take(12)?.value {
                    b"oskgp" => ParameterOperation::PublicIdentity,
                    b"oc" => ParameterOperation::CreateReference,
                    b"osa" => ParameterOperation::AttestReference,
                    b"osgn" => ParameterOperation::SignReference,
                    _ => return Err(refuse!("SEP system-key operation is not implemented")),
                });
            }
            b"skt" => {
                if key_type || der::unsigned(entry.take(2)?.value)? != [IDENTITY_TYPE as u8] {
                    return Err(refuse!("SEP system-key type is not implemented"));
                }
                key_type = true;
            }
            b"skg" => {
                if generation || der::unsigned(entry.take(2)?.value)? != [IDENTITY_GENERATION as u8]
                {
                    return Err(refuse!("SEP system-key generation is not implemented"));
                }
                generation = true;
            }
            b"bc" => reference_class = Some(parameter_number(&mut entry)?),
            b"kt" => reference_type = Some(parameter_number(&mut entry)?),
            b"rko" => reference_options = Some(parameter_number(&mut entry)?),
            b"rk" => reference_blob = Some(entry.take(17)?.encoded),
            b"d" => digest = Some(entry.take(4)?.value),
            _ => return Err(refuse!("SEP system-key parameter is not implemented")),
        }
        entry.end()?;
    }
    let reference_fields = [reference_class, reference_type, reference_options];
    match operation {
        Some(ParameterOperation::CreateReference) => {
            if key_type
                || generation
                || reference_blob.is_some()
                || digest.is_some()
                || reference_fields.iter().any(Option::is_none)
            {
                return Err(refuse!(
                    "SEP reference-key create dictionary is incomplete or mixed"
                ));
            }
            if transport_operation != 0 {
                return Err(refuse!(
                    "SEP reference-key create transport operation is not implemented"
                ));
            }
            if reference_class != Some(reference_key::CLASS) {
                return Err(refuse!("SEP reference-key class is not implemented"));
            }
            if reference_options != Some(reference_key::OPTIONS) {
                return Err(refuse!("SEP reference-key options are not implemented"));
            }
            let kind = reference_type.unwrap();
            if !matches!(kind, 4 | 5) {
                return Err(refuse!("SEP reference-key type is not implemented"));
            }
            Ok(Operation::CreateReference { kind })
        }
        Some(ParameterOperation::SignReference) => {
            if transport_operation != 0
                || key_type
                || generation
                || reference_fields.iter().any(Option::is_some)
            {
                return Err(refuse!(
                    "SEP reference-key signing parameters are not implemented"
                ));
            }
            let blob =
                reference_blob.ok_or(refuse!("SEP reference-key signing has no reference"))?;
            let digest = digest
                .ok_or(refuse!("SEP reference-key signing has no digest"))?
                .try_into()
                .map_err(|_| refuse!("SEP reference-key digest must be SHA-256 sized"))?;
            Ok(Operation::SignReference { blob, digest })
        }
        Some(ParameterOperation::AttestReference) => {
            if digest.is_some() {
                return Err(refuse!(
                    "SEP reference-key attestation contains signing data"
                ));
            }
            if transport_operation != 0
                || key_type
                || generation
                || reference_class.is_some()
                || reference_type.is_some()
                || reference_options.is_some_and(|v| v != reference_key::OPTIONS)
            {
                return Err(refuse!(
                    "SEP reference-key attestation parameters are not implemented"
                ));
            }
            let blob =
                reference_blob.ok_or(refuse!("SEP reference-key attestation has no reference"))?;
            Ok(Operation::AttestReference { blob })
        }
        Some(ParameterOperation::PublicIdentity) => {
            if !key_type || !generation {
                return Err(refuse!("SEP system-key dictionary is incomplete"));
            }
            if reference_fields.iter().any(Option::is_some)
                || reference_blob.is_some()
                || digest.is_some()
            {
                return Err(refuse!(
                    "SEP system-key public query carries reference-key parameters"
                ));
            }
            Ok(Operation::PublicIdentity)
        }
        None => Err(refuse!("SEP system-key dictionary is incomplete")),
    }
}

/// Sanitized metadata for a refused, digest-validated perform-operation.
/// Never render the session, unknown strings, parameter values or key bytes.
/// This parser only describes the request; it grants no operation or permission.
pub(super) fn diagnostic(variant: u32, fields: &mut Fields<'_>) -> String {
    let (mut handle, mut operation) = (None, None);
    let mut parameters = None;
    let parsed = (|| {
        let _session = fields.lword()?;
        handle = Some(fields.word()?);
        operation = Some(fields.word()?);
        let bytes = fields.blob()?;
        fields.end()?;
        parameters = Some(ParameterDiagnostic::parse(bytes)?);
        Ok::<_, stela_contracts::Refusal>(())
    })()
    .is_ok();
    let parameters = parameters.unwrap_or_default();
    format!(
        "sks refused command=0x22 variant={variant} handle={handle:?} operation={operation:?} parameter_operation={} system_key_type={:?} reference_key_type={:?} generation={:?} keys={} parsed={parsed} reference_key_class={:?} reference_key_options={:?}",
        parameters.operation,
        parameters.system_key_type,
        parameters.reference_key_type,
        parameters.generation,
        parameters.keys,
        parameters.reference_key_class,
        parameters.reference_key_options,
    )
}

struct ParameterDiagnostic {
    operation: &'static str,
    system_key_type: Option<u32>,
    reference_key_type: Option<u32>,
    generation: Option<u32>,
    reference_key_class: Option<u32>,
    reference_key_options: Option<u32>,
    /// Allowlisted key names in arrival order, `?` for any other key: the
    /// encoder's pair order, which the strict parser requires ascending.
    keys: String,
}

impl Default for ParameterDiagnostic {
    fn default() -> Self {
        Self {
            operation: "unknown",
            system_key_type: None,
            reference_key_type: None,
            generation: None,
            reference_key_class: None,
            reference_key_options: None,
            keys: String::new(),
        }
    }
}

impl ParameterDiagnostic {
    fn parse(bytes: &[u8]) -> Result<Self> {
        let mut outer = Cursor(bytes);
        let set = outer.take(17)?;
        outer.end()?;
        let mut pairs = Cursor(set.value);
        let mut result = Self::default();
        let mut has_operation = false;
        // Bounded diagnostic work even for a large, otherwise valid request.
        for _ in 0..32 {
            if pairs.0.is_empty() {
                return Ok(result);
            }
            let pair = pairs.take(16)?;
            let mut entry = Cursor(pair.value);
            let key = entry.take(12)?.value;
            if !result.keys.is_empty() {
                result.keys.push(',');
            }
            result.keys.push_str(match key {
                b"o" => "o",
                b"skt" => "skt",
                b"kt" => "kt",
                b"skg" => "skg",
                b"bc" => "bc",
                b"rko" => "rko",
                b"rk" => "rk",
                b"d" => "d",
                _ => "?",
            });
            match key {
                b"o" => {
                    if has_operation {
                        return Err(refuse!("SEP diagnostic operation is duplicated"));
                    }
                    has_operation = true;
                    // Original operation names only. Unknown guest strings
                    // may contain secrets and must never enter a log line.
                    result.operation = match entry.take(12)?.value {
                        b"oskgp" => "oskgp",
                        b"oc" => "oc",
                        b"osgn" => "osgn",
                        b"osa" => "osa",
                        b"oskc" => "oskc",
                        b"oska" => "oska",
                        b"osko" => "osko",
                        _ => "unknown",
                    };
                }
                b"skt" if result.system_key_type.is_none() => {
                    result.system_key_type = Some(parameter_number(&mut entry)?);
                }
                b"kt" if result.reference_key_type.is_none() => {
                    result.reference_key_type = Some(parameter_number(&mut entry)?);
                }
                b"skg" if result.generation.is_none() => {
                    result.generation = Some(parameter_number(&mut entry)?);
                }
                b"bc" if result.reference_key_class.is_none() => {
                    result.reference_key_class = Some(parameter_number(&mut entry)?);
                }
                b"rko" if result.reference_key_options.is_none() => {
                    result.reference_key_options = Some(parameter_number(&mut entry)?);
                }
                b"skt" | b"kt" | b"skg" | b"bc" | b"rko" => {
                    return Err(refuse!("SEP diagnostic number is duplicated"));
                }
                _ => {
                    entry.next()?;
                }
            }
            entry.end()?;
        }
        Err(refuse!(
            "SEP diagnostic dictionary exceeds the parameter bound"
        ))
    }
}

fn parameter_number(entry: &mut Cursor<'_>) -> Result<u32> {
    let bytes = der::unsigned(entry.take(2)?.value)?;
    if bytes.len() > 4 {
        return Err(refuse!("SEP keystore integer is oversized"));
    }
    Ok(bytes.iter().fold(0, |n, b| (n << 8) | u32::from(*b)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identity_is_a_real_curve_key_and_reopens_without_new_entropy() {
        let root = Zeroizing::new([1; 32]);
        let mut first = SystemKeys::new(root.clone());
        let public = first.public(PublicQuery::Identity).unwrap().to_vec();
        p256::PublicKey::from_sec1_bytes(&public).unwrap();
        assert_eq!(public.len(), PUBLIC_BYTES);
        assert_eq!(public[0], 4);
        // Independent Python HMAC + OpenSSL EC public-key derivation for
        // this test-only seed and the exact domain/type/generation/counter.
        assert_eq!(
            hex::encode(&public),
            "04c5f1cca66ff986742be7e6ccf4996fde1a031bf7697cf7fe104b23a82f98c5c3d908693dbc7b4df331a1940e69526c8417327beab5ca48fd505e2337bcdff437"
        );
        assert_eq!(public, first.public(PublicQuery::Identity).unwrap());
        let mut reopened = SystemKeys::new(root);
        assert_eq!(public, reopened.public(PublicQuery::Identity).unwrap());
        let mut other = SystemKeys::new(Zeroizing::new([2; 32]));
        assert_ne!(public, other.public(PublicQuery::Identity).unwrap());
    }
}
