//! The per-chip IMPLEMENTATION DEFINED census that `machine::impdef` keys
//! its table by: for each [`Chip`], every System register encoding (op0 3,
//! CRn 11 and 15) that the SPTM, TXM or kernelcache of one of its SoCs
//! accesses, from the facts' `impdef` rows. Only SoCs with a `machine::soc`
//! row ([`soc::chip`]) count.
use anyhow::{Context, Result, ensure};
use serde_json::Value;
use std::{collections::BTreeSet, fmt::Write as _};
use stela_compiler::aarch64::system::registers::Encoding;
use stela_runtime::machine::{Chip, soc};

/// The generated module, relative to the repository root.
pub const OUTPUT: &str = "crates/stela-runtime/src/machine/impdef/census.rs";
/// The fact groups whose rows name a component's accesses.
const GROUPS: [&str; 3] = ["socs", "monitors", "kernels"];
/// Selectors per generated line.
const PER_LINE: usize = 10;
/// The System register op0.
const REGISTER_OP0: u8 = 3;

/// `S<op0>_<op1>_C<n>_C<m>_<op2>` as an encoding.
fn parse(name: &str) -> Option<Encoding> {
    let mut fields = name.split('_');
    let op0 = fields.next()?.strip_prefix('S')?.parse().ok()?;
    let op1 = fields.next()?.parse().ok()?;
    let crn = fields.next()?.strip_prefix('C')?.parse().ok()?;
    let crm = fields.next()?.strip_prefix('C')?.parse().ok()?;
    let op2 = fields.next()?.parse().ok()?;
    fields
        .next()
        .is_none()
        .then(|| Encoding::new(op0, op1, crn, crm, op2))
}

fn chip_of(id: &Value) -> Result<Option<Chip>> {
    let id = id.as_str().context("a chip id is not a string")?;
    let id = u32::from_str_radix(id.trim_start_matches("0x"), 16)
        .with_context(|| format!("chip id {id} is not hexadecimal"))?;
    Ok(soc::chip(id))
}

/// Each chip's sorted register selectors, in [`Chip::ALL`] order.
pub fn consumed(facts: &Value) -> Result<Vec<BTreeSet<u16>>> {
    let mut consumed = vec![BTreeSet::new(); Chip::ALL.len()];
    for group in GROUPS {
        let entries = facts[group]
            .as_array()
            .with_context(|| format!("the facts have no {group} list"))?;
        for entry in entries {
            let chips = entry["chip_ids"]
                .as_array()
                .context("a group has no chip ids")?
                .iter()
                .map(chip_of)
                .collect::<Result<Vec<_>>>()?;
            let rows = entry["impdef"]
                .as_array()
                .context("a group has no census")?;
            for row in rows {
                let name = row[0].as_str().context("a census row has no encoding")?;
                let encoding =
                    parse(name).with_context(|| format!("census encoding {name} is malformed"))?;
                if encoding.op0() != REGISTER_OP0 {
                    continue;
                }
                for chip in chips.iter().flatten() {
                    consumed[*chip as usize].insert(encoding.selector());
                }
            }
        }
    }
    Ok(consumed)
}

/// The generated `machine::impdef::census` module.
pub fn rust(facts: &Value) -> Result<String> {
    let consumed = consumed(facts)?;
    let manifest = facts["source"]["manifest_sha256"]
        .as_str()
        .context("the facts name no manifest")?;
    let build = facts["source"]["product_build"].as_str().unwrap_or("?");
    let mut text = String::new();
    writeln!(
        text,
        "//! Generated by `cargo xtask soc-facts` from `isa/apple-soc-facts.json`\n\
         //! (build {build}, BuildManifest SHA-256\n\
         //! {manifest}); do not edit.\n\
         //!\n\
         //! For each chip, in `Chip::ALL` order, the IMPLEMENTATION DEFINED System\n\
         //! register encodings (op0 3, CRn 11 and 15) that the SPTM, TXM or\n\
         //! kernelcache of one of its SoCs (`machine::soc` rows) reads or writes,\n\
         //! as sorted `Encoding::selector` values.\n\
         \n\
         #[rustfmt::skip]\n\
         pub const CONSUMED: [&[u16]; {}] = [",
        Chip::ALL.len()
    )?;
    for (chip, selectors) in Chip::ALL.iter().zip(&consumed) {
        ensure!(!selectors.is_empty(), "{} has no census rows", chip.name());
        writeln!(
            text,
            "    // {}: {} encodings",
            chip.name(),
            selectors.len()
        )?;
        writeln!(text, "    &[")?;
        let selectors: Vec<String> = selectors.iter().map(|s| format!("{s:#06x}")).collect();
        for line in selectors.chunks(PER_LINE) {
            writeln!(text, "        {},", line.join(", "))?;
        }
        writeln!(text, "    ],")?;
    }
    writeln!(text, "];")?;
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn rows_count_once_per_chip_and_only_registers() {
        assert_eq!(parse("S3_4_C15_C0_1"), Some(Encoding::new(3, 4, 15, 0, 1)));
        assert_eq!(parse("S3_4_C15_C0"), None);
        let facts = json!({
            "socs": [{"chip_ids": ["0x8112", "0x6020"], "impdef": [
                ["S3_0_C15_C0_0", "read", 9, null, "0x0", "0x0"],
                ["S3_0_C15_C0_0", "write", 9, null, "0x0", "0x0"],
                ["S1_0_C11_C0_0", "write", 1, null, "0x0", "0x0"],
            ]}],
            "monitors": [{"chip_ids": ["0x8103"], "impdef": []}],
            "kernels": [{"chip_ids": ["0x8103", "0x6050"], "impdef": [
                ["S3_7_C15_C1_1", "read", 2, "com.apple.kernel", "0x0", "0x0"],
            ]}],
        });
        let consumed = consumed(&facts).unwrap();
        let hid0 = Encoding::new(3, 0, 15, 0, 0).selector();
        let energy = Encoding::new(3, 7, 15, 1, 1).selector();
        assert_eq!(consumed[Chip::AppleM2 as usize], BTreeSet::from([hid0]));
        // A chip without a row (0x6050) adds nothing; the M1 has the kernel's.
        assert_eq!(consumed[Chip::AppleM1 as usize], BTreeSet::from([energy]));
        assert!(consumed[Chip::AppleM5 as usize].is_empty());
    }
}
