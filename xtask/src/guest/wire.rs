//! `StelaGPU/Wire.h`: the Metal service's wire format as C, generated from its
//! declarations in `stela-driver-gpu`, so the bundle and the service share one
//! statement of every record, code and capability.
//!
//! The declarations are regular by construction (rustfmt's layout of
//! `records!`, `raw_enum!`, `option_set!` and `operations!`), and C's layout of
//! a structure with no padding is `repr(C)`'s, so reading them line by line is
//! enough. What this does not understand fails the bundle's build, as the C
//! compiler then lacks a name.
use anyhow::{Context, Result, bail};
use std::{fmt::Write, fs, path::Path};

/// The declaring files, each using only what comes before it.
const SOURCES: [&str; 3] = [
    "capabilities/block.rs",
    "service/wire.rs",
    "service/wire/commands.rs",
];

/// Writes `<include>/StelaGPU/Wire.h`.
pub fn generate(metal: &Path, include: &Path) -> Result<()> {
    let mut sources = Vec::new();
    for source in SOURCES {
        let path = metal.join(source);
        let text = fs::read_to_string(&path).with_context(|| format!("{}", path.display()))?;
        sources.push(text);
    }
    let directory = include.join("StelaGPU");
    fs::create_dir_all(&directory)?;
    fs::write(directory.join("Wire.h"), header(&sources)?)?;
    Ok(())
}

/// A primitive's C type, or the generated name of a record.
fn c_type(name: &str) -> String {
    let name = name.rsplit("::").next().unwrap_or(name);
    match name {
        "u8" => "uint8_t".into(),
        "u32" => "uint32_t".into(),
        "u64" => "uint64_t".into(),
        "i32" => "int32_t".into(),
        "i64" => "int64_t".into(),
        "f32" => "float".into(),
        "f64" => "double".into(),
        record => format!("Stela{record}"),
    }
}

/// A field as C declares it: `[[T; N]; M]` puts its lengths after the name,
/// the outermost first.
fn c_field(name: &str, ty: &str) -> Result<String> {
    let mut element = ty;
    let mut lengths = String::new();
    while let Some(inner) = element.strip_prefix('[') {
        let inner = inner.strip_suffix(']').context("an array type")?;
        let (next, length) = inner.rsplit_once("; ").context("an array type")?;
        let constant = length.chars().next().is_some_and(char::is_alphabetic);
        let prefix = if constant { "STELA_" } else { "" };
        write!(lengths, "[{prefix}{length}]")?;
        element = next;
    }
    Ok(format!("{} {name}{lengths}", c_type(element)))
}

/// What the lines being read declare.
enum Within {
    Nothing,
    /// A `macro_rules!`, whose templates look like declarations.
    Macro,
    Records,
    Record(String),
    Enum(String),
    Flags(String),
    Operations,
}

/// The header declaring `sources`' records, constants, codes and operations.
fn header(sources: &[String]) -> Result<String> {
    let mut out = String::from(concat!(
        "/* Generated by `cargo xtask guest` from stela-driver-gpu's wire format. */\n",
        "#pragma once\n#include <stdint.h>\n\n",
    ));
    let mut operations = String::new();
    for source in sources {
        let mut within = Within::Nothing;
        let mut packed = false;
        for raw in source.lines() {
            let line = raw.trim();
            if line.starts_with("//") || line.starts_with("#[doc") {
                continue;
            }
            within = match within {
                Within::Macro if raw == "}" => Within::Nothing,
                Within::Macro => Within::Macro,
                Within::Nothing if raw.starts_with("macro_rules!") => Within::Macro,
                Within::Nothing | Within::Records => {
                    let in_records = matches!(within, Within::Records);
                    let next = if in_records {
                        Within::Records
                    } else {
                        Within::Nothing
                    };
                    if line == "#[repr(C)]" {
                        packed = true;
                        next
                    } else if line == "records! {" {
                        Within::Records
                    } else if line == "operations! {" {
                        Within::Operations
                    } else if raw == "}" {
                        Within::Nothing
                    } else if let Some(name) = declared(line, "pub struct ", " {}") {
                        writeln!(out, "typedef struct {{}} {};\n", c_type(name))?;
                        next
                    } else if let Some(name) = declared(line, "pub struct ", " {") {
                        if let Some((name, _)) = name.split_once(": ") {
                            Within::Flags(name.into())
                        } else if in_records || packed {
                            writeln!(out, "typedef struct {{")?;
                            Within::Record(name.into())
                        } else {
                            next
                        }
                    } else if let Some(name) = declared(line, "pub enum ", " {") {
                        match name.split_once(": ") {
                            Some((name, _)) => {
                                writeln!(out, "enum {{")?;
                                Within::Enum(name.into())
                            }
                            None => next,
                        }
                    } else {
                        if !in_records && raw == line {
                            constant(line, &mut out)?;
                        }
                        next
                    }
                }
                Within::Record(name) => {
                    if line == "}" {
                        writeln!(out, "}} {};\n", c_type(&name))?;
                        packed = false;
                        // A `#[repr(C)]` structure closes in column zero, a
                        // record in `records!` further in.
                        if raw == "}" {
                            Within::Nothing
                        } else {
                            Within::Records
                        }
                    } else {
                        if let Some(field) = line.strip_prefix("pub ") {
                            let field = field.strip_suffix(',').context(field.to_owned())?;
                            let (field, ty) = field.split_once(": ").context(field.to_owned())?;
                            writeln!(out, "\t{};", c_field(field, ty)?)?;
                        }
                        Within::Record(name)
                    }
                }
                Within::Enum(name) => {
                    if line == "}" {
                        writeln!(out, "}};\n")?;
                        Within::Nothing
                    } else {
                        if let Some((variant, value)) = line.split_once(" = ") {
                            let value = value.strip_suffix(',').context(line.to_owned())?;
                            writeln!(out, "\tStela{name}{variant} = {value},")?;
                        }
                        Within::Enum(name)
                    }
                }
                Within::Flags(name) => {
                    if line == "}" {
                        out.push('\n');
                        Within::Nothing
                    } else {
                        if let Some(flag) = line.strip_prefix("const ") {
                            let flag = flag.strip_suffix(';').context(line.to_owned())?;
                            let (flag, value) = flag.split_once(" = ").context(line.to_owned())?;
                            let value = value.replacen("1 <<", "1ull <<", 1);
                            writeln!(out, "#define Stela{name}_{flag} ({value})")?;
                        }
                        Within::Flags(name)
                    }
                }
                Within::Operations => {
                    if raw == "}" {
                        Within::Nothing
                    } else {
                        if let Some((name, records)) = line.split_once(" => ") {
                            let (name, code) = name.split_once(" = ").context(line.to_owned())?;
                            let records = records.strip_suffix(';').context(line.to_owned())?;
                            let (request, response) =
                                records.split_once(", ").context(line.to_owned())?;
                            writeln!(operations, "#define StelaOperation{name} {code}")?;
                            let (request, response) = (c_type(request), c_type(response));
                            writeln!(operations, "typedef {request} Stela{name}Call;")?;
                            writeln!(operations, "typedef {response} Stela{name}Reply;")?;
                        }
                        Within::Operations
                    }
                }
            };
        }
        if !matches!(within, Within::Nothing) {
            bail!("a declaration runs past the end of its file");
        }
    }
    out.push_str(&operations);
    Ok(out)
}

/// The name in `<prefix>name<suffix>`.
fn declared<'a>(line: &'a str, prefix: &str, suffix: &str) -> Option<&'a str> {
    line.strip_prefix(prefix)?.strip_suffix(suffix)
}

/// An integer `pub const` as a macro.
fn constant(line: &str, out: &mut String) -> Result<()> {
    let Some(declaration) = declared(line, "pub const ", ";") else {
        return Ok(());
    };
    let Some((name, value)) = declaration.split_once(" = ") else {
        return Ok(());
    };
    let Some((name, ty)) = name.split_once(": ") else {
        return Ok(());
    };
    if !matches!(ty, "u8" | "u32" | "u64" | "usize") {
        return Ok(());
    }
    let value = match value {
        "u32::MAX" => "UINT32_MAX",
        "u64::MAX" => "UINT64_MAX",
        value => value,
    };
    writeln!(out, "#define STELA_{name} {value}\n")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_declaration_becomes_c() {
        let block = "pub const FAMILIES: usize = 32;\n\
                     pub const MAGIC: [u8; 4] = *b\"STCB\";\n\
                     option_set! {\n    /// Flags.\n    pub struct Flags: u64 {\n        \
                     const HEADLESS = 1 << 32;\n    }\n}\n\
                     #[repr(C)]\n#[derive(Clone)]\npub struct Block {\n    \
                     /// Field.\n    pub magic: [u8; 4],\n    \
                     pub families: [u64; FAMILIES],\n}\n\
                     pub struct Other {\n    pub ignored: u32,\n}\n";
        let wire = "records! {\n    pub struct Empty {}\n\n    pub struct Span {\n        \
                    pub address: u64,\n    }\n\n    pub struct Pair {\n        \
                    pub spans: [Span; 2],\n    }\n}\n\
                    raw_enum! {\n    pub enum Status: u32 {\n        Ok = 0,\n        \
                    Bad = 0x10,\n    }\n}\n\
                    operations! {\n    /// Agrees.\n    \
                    Negotiate = 0x0001 => Empty, commands::Pair;\n}\n\
                    pub const NO_TYPE: u32 = u32::MAX;\n";
        let header = header(&[block.into(), wire.into()]).unwrap();
        for expected in [
            "#define STELA_FAMILIES 32\n",
            "#define StelaFlags_HEADLESS (1ull << 32)\n",
            "typedef struct {\n\tuint8_t magic[4];\n\tuint64_t families[STELA_FAMILIES];\n} StelaBlock;",
            "typedef struct {} StelaEmpty;",
            "typedef struct {\n\tStelaSpan spans[2];\n} StelaPair;",
            "\tStelaStatusBad = 0x10,\n",
            "#define StelaOperationNegotiate 0x0001\n",
            "typedef StelaEmpty StelaNegotiateCall;\ntypedef StelaPair StelaNegotiateReply;\n",
            "#define STELA_NO_TYPE UINT32_MAX\n",
        ] {
            assert!(header.contains(expected), "{expected}\nin\n{header}");
        }
        assert!(!header.contains("MAGIC") && !header.contains("Other"));
    }

    #[test]
    fn a_declaration_left_open_is_refused() {
        assert!(header(&["records! {\n    pub struct Span {\n".into()]).is_err());
    }
}
